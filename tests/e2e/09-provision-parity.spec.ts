import { test, expect } from '@playwright/test';

/**
 * Provisioning Parity Test — Founder Emergency Provision vs Website Purchase.
 *
 * Both paths now call the SAME production pipeline on the Main Website:
 *   POST /api/provisioning/emergency → provisionChallenge → @workspace/products
 *
 * The Admin panel owns NO challenge config, account sizes, risk rules,
 * provisioning logic or credential generation. Everything is read from the
 * single source of truth (@workspace/products) via the production API.
 *
 * These tests skip gracefully when the environment is not fully wired
 * (no Founder auth session, or the Main Website API is not reachable).
 */

const NOT_READY = [401, 403, 500, 502, 503, 504];

test.describe('Provision Parity: Emergency uses production pipeline', () => {
  test.use({ storageState: 'tests/e2e/.auth/founder.json' });

  test('GET catalog comes from the production single source of truth', async ({ request }) => {
    const res = await request.get('/api/founder/emergency-provision');
    if (NOT_READY.includes(res.status())) {
      test.skip(true, 'Environment not fully wired (auth or Main Website API unavailable)');
      return;
    }
    expect(res.status()).toBe(200);
    const { products } = await res.json();
    expect(products.length).toBe(4);

    const slugs = products.map((p: any) => p.slug).sort();
    expect(slugs).toEqual(['1step', '2step', 'flash', 'instant']);

    // Canonical production values (from @workspace/products).
    const expected: Record<string, any> = {
      flash: { profitTargetPct: 10, dailyDrawdownLimitPct: 3, maxDrawdownLimitPct: 6, minTradingDays: 3, accountSizes: [50000, 100000, 250000, 500000, 1000000] },
      instant: { profitTargetPct: 10, dailyDrawdownLimitPct: 3, maxDrawdownLimitPct: 6, minTradingDays: 1, accountSizes: [100000, 500000, 1000000] },
      '1step': { profitTargetPct: 10, dailyDrawdownLimitPct: 4, maxDrawdownLimitPct: 8, minTradingDays: 5, accountSizes: [100000, 500000, 1000000, 2500000] },
      '2step': { profitTargetPct: 8, dailyDrawdownLimitPct: 4, maxDrawdownLimitPct: 10, minTradingDays: 5, accountSizes: [500000, 1000000, 2500000] },
    };

    for (const [slug, e] of Object.entries(expected)) {
      const p = products.find((x: any) => x.slug === slug);
      expect(p, `product ${slug}`).toBeDefined();
      expect(p.profitTargetPct, `${slug}.profitTargetPct`).toBe(e.profitTargetPct);
      expect(p.dailyDrawdownLimitPct, `${slug}.dailyDrawdownLimitPct`).toBe(e.dailyDrawdownLimitPct);
      expect(p.maxDrawdownLimitPct, `${slug}.maxDrawdownLimitPct`).toBe(e.maxDrawdownLimitPct);
      expect(p.minTradingDays, `${slug}.minTradingDays`).toBe(e.minTradingDays);
      expect(p.accountSizes, `${slug}.accountSizes`).toEqual(e.accountSizes);
      expect(p.leverage, `${slug}.leverage`).toBe('1:100');
    }
  });

  test('Emergency provision returns a production account (account_code, no generated password)', async ({ request }) => {
    const email = `parity-emergency-${Date.now()}@test.fundedwealth.com`;
    const res = await request.post('/api/founder/emergency-provision', {
      data: { name: 'Parity A', email, challenge_type: '1step', account_size: 100000 },
    });
    if (NOT_READY.includes(res.status())) {
      test.skip(true, 'Environment not fully wired');
      return;
    }
    expect(res.status()).toBe(200);
    const { data } = await res.json();

    // Production account identifiers — generated by provisionChallenge, not Admin.
    expect(data.account_code).toMatch(/^FW-/);
    expect(data.password).toBeUndefined();
    expect(data.challenge_account_id).toBeTruthy();
    expect(data.trading_account_id).toBeTruthy();

    // Risk settings come from @workspace/products (1-step).
    expect(data.challenge_type).toBe('1step');
    expect(data.account_size).toBe(100000);
    expect(data.profit_target_pct).toBe(10);
    expect(data.daily_drawdown_limit_pct).toBe(4);
    expect(data.max_drawdown_limit_pct).toBe(8);
    expect(data.leverage).toBe('1:100');
  });

  test('Invalid challenge type is rejected', async ({ request }) => {
    const res = await request.post('/api/founder/emergency-provision', {
      data: { name: 'X', email: `bad-type-${Date.now()}@test.fundedwealth.com`, challenge_type: 'evaluation', account_size: 100000 },
    });
    if (NOT_READY.includes(res.status())) {
      test.skip(true, 'Environment not fully wired');
      return;
    }
    expect(res.status()).toBe(400);
    const json = await res.json();
    expect(json.error.message).toContain('Invalid challenge type');
  });

  test('Invalid account size is rejected', async ({ request }) => {
    const res = await request.post('/api/founder/emergency-provision', {
      data: { name: 'X', email: `bad-size-${Date.now()}@test.fundedwealth.com`, challenge_type: 'flash', account_size: 12345 },
    });
    if (NOT_READY.includes(res.status())) {
      test.skip(true, 'Environment not fully wired');
      return;
    }
    expect(res.status()).toBe(400);
    const json = await res.json();
    expect(json.error.message).toContain('not a valid size');
  });
});
